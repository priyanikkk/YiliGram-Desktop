QPainterPath ShapePath(Shape shape, const QRectF &rect) {
	auto transform = QTransform();
	transform.translate(rect.x(), rect.y());
	transform.scale(rect.width(), rect.height());
	return transform.map(UnitPath(shape));
}

AvatarFrame CurrentAvatarFrame() {
	return Frame;
}

void SetAvatarFrame(AvatarFrame frame) {
	if (Frame != frame) {
		Frame = frame;
		++FrameVersion;
	}
}

int AvatarFrameVersion() {
	return FrameVersion;
}

QPainterPath AvatarFramePath(AvatarFrame frame, const QRectF &rect) {
	const auto shape = [&]() -> std::optional<Shape> {
		switch (frame) {
		case AvatarFrame::Cookie9: return Shape::Cookie9;
		case AvatarFrame::Cookie12: return Shape::Cookie12;
		case AvatarFrame::Clover4: return Shape::Clover4;
		case AvatarFrame::Sunny: return Shape::Sunny;
		case AvatarFrame::SoftBurst: return Shape::SoftBurst;
		case AvatarFrame::Flower: return Shape::Flower;
		case AvatarFrame::Pentagon: return Shape::Pentagon;
		case AvatarFrame::Gem: return Shape::Gem;
		case AvatarFrame::Square: return Shape::Square;
		case AvatarFrame::Circle: break;
		}
		return std::nullopt;
	}();
	if (!shape) {
		auto result = QPainterPath();
		result.addEllipse(rect);
		return result;
	}
	return ShapePath(*shape, rect);
}

QPainterPath AvatarFramePath(const QRectF &rect) {
	return AvatarFramePath(Frame, rect);
}

QImage ApplyAvatarFrame(QImage image) {
	if (Frame == AvatarFrame::Circle || image.isNull()) {
		return Images::Circle(std::move(image));
	}
	if (image.format() != QImage::Format_ARGB32_Premultiplied) {
		image = std::move(image).convertToFormat(
			QImage::Format_ARGB32_Premultiplied);
	}
	auto mask = QImage(image.size(), QImage::Format_ARGB32_Premultiplied);
	mask.fill(Qt::transparent);
	{
		auto p = QPainter(&mask);
		auto hq = PainterHighQualityEnabler(p);
		p.setPen(Qt::NoPen);
		p.setBrush(Qt::white);
		p.drawPath(AvatarFramePath(QRectF(QPointF(), QSizeF(image.size()))));
	}
	{
		auto p = QPainter(&image);
		p.setCompositionMode(QPainter::CompositionMode_DestinationIn);
		p.drawImage(0, 0, mask);
	}
	return image;
}

