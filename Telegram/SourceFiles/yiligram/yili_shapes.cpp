template <size_t N>
QPainterPath Build(const float (&points)[N]) {
	static_assert(N % 8 == 0);
	auto result = QPainterPath();
	result.moveTo(points[0], points[1]);
	for (auto i = size_t(0); i != N; i += 8) {
		result.cubicTo(
			points[i + 2], points[i + 3],
			points[i + 4], points[i + 5],
			points[i + 6], points[i + 7]);
	}
	result.closeSubpath();
	return result;
}

const QPainterPath &UnitPath(Shape shape) {
	static const auto paths = std::array<QPainterPath, 10>{
		Build(kCookie4),
		Build(kCookie9),
		Build(kCookie12),
		Build(kClover4),
		Build(kSunny),
		Build(kSoftBurst),
		Build(kFlower),
		Build(kPentagon),
		Build(kGem),
		Build(kSquare),
	};
	return paths[static_cast<int>(shape)];
}

auto Frame = AvatarFrame::Circle;
auto FrameVersion = 0;

